// The site's `packages:` frontmatter as a list — comma-separated, entries trimmed. SiteLayout's own
// parse (it decides `hasPwa`, and so which apple-touch-icon iconHrefs() hands back), and the feed's.
//
// 🩸 tile#177 r3: the RSS <image> re-derived `hasPwa` with a whitespace split beside the layout's
// comma split, so `packages: blog pwa` kept the owner's PNG in <head> while the feed named the PWA
// badge. One parse, imported by both, so the two cannot disagree on which packages are on.
//
// Its own file, not icon-core: cardtile's /try/edit bundle stamps icon-core's bytes, and a helper
// the Card never calls should not make that bundle stale. Zero deps, plain node, no Vite alias.
export const sitePackages = (meta) => String((meta && meta.packages) || '').split(',').map((s) => s.trim()).filter(Boolean);

// REEF with Site — the agent-readable artifacts: llms.txt, llms-full.txt, one markdown
// representation per public static route, the /.well-known/ai-catalog.json discovery list, and the
// internal route→markdown mapping the site worker consumes.
//
// Deliberately OUT of the route files and free of `import.meta.glob`, so a plain `node --test` can
// reach every builder here — the same reason lib/sitemap.mjs sits beside pages/sitemap.xml.js. The
// glob-carrying seam that feeds this module is lib/agent-corpus.mjs; it is the only part of this
// feature a test cannot execute, and it holds no rules.
//
// PRIVACY. This renderer has ONE privacy verdict (lib/blog.mjs) and this file uses it rather than
// growing a second: publicFacing() strips body/description/excerpt from a private post BEFORE
// anything here serializes it, and isPrivatePost() decides which documents get no markdown
// representation, no entry in llms-full.txt and no line in the worker mapping at all. What a
// private post keeps in llms.txt is its title and its path — the same non-content metadata the
// feed and the search index already carry, and nothing more.
//
// PROVENANCE. Every document carries its canonical URL and its title in a header separated from
// the content. Site prose is site-authored DATA: nothing here rewrites it into an instruction
// addressed to whoever reads it, and nothing here claims to sanitize it.
import { isPrivatePost, publicFacing } from './blog.mjs';
import { canonicalPath } from './sitemap.mjs';

/** Implementation safety guard, NOT a canonical contract: over this many UTF-8 bytes the full-text
 *  dump is not emitted at all. A truncated corpus is worse than an absent one — it reads as a
 *  complete site to anything that fetched it, and the catalog can say `null` honestly. */
export const LLMS_FULL_MAX_BYTES = 2 * 1024 * 1024;

/** The one line that marks an artifact as platform-generated. A hand-written llms.txt shipped
 *  through the owner's own assets does not carry it, which is what lets verification tell an
 *  owner's file apart from ours without guessing. Same wording family as the compiled robots.txt
 *  header, and the same single source: the site's `ai-usage`. */
export const GENERATED_BY = 'Generated by feelreef from `ai-usage` in ir/_site.md';

/** The neutral build gate, read from the environment the build orchestration exports.
 *  This side owns NO policy vocabulary: `cite`/`train`/`search-only` are resolved once, in Reef,
 *  and arrive here as a boolean plus one collision fact. */
export function agentGate(env) {
  const e = env || {};
  const generate = String(e.SITETILE_AGENT_ARTIFACTS || '') === '1';
  return { generate, manualLlms: generate && String(e.SITETILE_AGENT_LLMS_MANUAL || '') === '1' };
}

/** A route's markdown asset path, mirroring the HTML output shape: `/about/` → `/about/index.md`,
 *  `/` → `/index.md`. Derived from the path the build actually emitted, never from a URL family. */
export function markdownAsset(path) {
  return canonicalPath(path).replace(/\/$/, '') + '/index.md';
}

// Only ever applied INSIDE a `[…]` label, where a stray bracket would break the link. A heading
// is left exactly as the author wrote it — the renderer runs `##` titles through inline markdown
// too, so escaping here would make the projection less faithful, not safer.
const escLabel = (s) => String(s == null ? '' : s).replace(/([[\]])/g, '\\$1');

/** Site prose with the family's `%% … %%` control comments removed (the `%% sitetile: <type> %%`
 *  layout line is consumed by the parser; any sibling comment is build vocabulary, not content),
 *  trailing whitespace trimmed and blank runs collapsed. */
function cleanBody(body) {
  return String(body || '')
    .replace(/%%[\s\S]*?%%/g, '')
    .split('\n')
    .map((line) => line.replace(/[ \t]+$/, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function child(level, title, href, body, out) {
  const label = String(title || '').trim();
  if (label) out.push(level + ' ' + (href ? `[${escLabel(label)}](${href})` : label));
  const text = cleanBody(body);
  if (text) out.push(text);
}

/** One parsed section → the markdown a reader would recognise: its heading, its prose, and the
 *  headings/links/bodies of whatever it holds. Fidelity of every coral is NOT the goal — nothing
 *  private and nothing internal leaking is. `embed` is skipped for the reason deriveDescription
 *  skips it: its body is raw HTML/JS, not prose anyone wrote to be read. `form` fields are input
 *  structure, not content, so a form keeps its heading and its lead and loses its inputs. */
function sectionMarkdown(section) {
  const s = section || {};
  const out = [];
  const title = String(s.title || '').trim();
  if (title) out.push('## ' + title);
  if (s.type !== 'embed') {
    const body = cleanBody(s.body);
    if (body) out.push(body);
  }
  for (const c of s.cells || []) child('###', c.title, c.href, c.body, out);
  for (const g of s.groups || []) {
    child('###', g.title, '', g.lead, out);
    for (const p of g.people || []) child('####', p.title, p.href, p.body, out);
    for (const it of g.items || []) child('####', it.title, it.href, it.body, out);
  }
  for (const e of s.entries || []) {
    child('###', [e.year, e.title].filter(Boolean).join(' — '), '', e.body, out);
  }
  for (const f of s.faqs || []) child('###', f.q, '', f.body, out);
  return out.join('\n\n');
}

function absoluteUrl(origin, path) {
  return String(origin || '').replace(/\/$/, '') + canonicalPath(path);
}

/** One document's markdown file: a small provenance header (title + the canonical URL this text
 *  was published at), then the content. The header is YAML so metadata and content are separated
 *  by the document's own grammar rather than by a convention a reader has to be told about. */
export function documentMarkdown(doc, origin) {
  const head = [
    '---',
    'title: ' + JSON.stringify(String(doc.title || '')),
    'source: ' + absoluteUrl(origin, doc.path),
    '---',
  ].join('\n');
  const body = String(doc.body || '').trim();
  return head + '\n' + (body ? '\n' + body + '\n' : '');
}

/** A content page → a corpus document. `sections` is parseSite()'s own section list, so what lands
 *  here is the model the renderer paints, not the raw file. */
export function pageDoc({ path, title, summary, sections }) {
  const p = canonicalPath(path);
  const heading = String(title || '').trim();
  const body = [
    ...(heading ? ['# ' + heading] : []),
    ...(sections || []).map(sectionMarkdown).filter(Boolean),
  ].join('\n\n');
  return { kind: 'page', path: p, title: heading, summary: String(summary || '').trim(), private: false, body };
}

/** A post → a corpus document, through publicFacing() so a private post arrives already emptied of
 *  body, description and excerpt. `private` rides along because llms.txt is the ONE artifact that
 *  may still name it. */
export function postDoc({ path, post }) {
  const gated = isPrivatePost(post);
  const p = publicFacing(post || {});
  const heading = String(p.title || '').trim();
  const body = gated ? '' : [
    ...(heading ? ['# ' + heading] : []),
    cleanBody(p.body),
  ].filter(Boolean).join('\n\n');
  return {
    kind: 'post',
    path: canonicalPath(path),
    title: heading,
    summary: gated ? '' : String(p.description || p.excerpt || '').trim(),
    private: gated,
    body,
  };
}

/** Every document that gets a markdown representation: public documents only, in corpus order. */
export function publicDocs(corpus) {
  return (corpus.docs || []).filter((d) => !d.private);
}

export function buildLlmsTxt(corpus) {
  const site = corpus.site || {};
  const out = ['# ' + String(site.name || '').trim()];
  const description = String(site.description || '').trim();
  if (description) out.push('> ' + description);
  for (const [heading, kind] of [['Pages', 'page'], ['Posts', 'post']]) {
    const docs = (corpus.docs || []).filter((d) => d.kind === kind);
    if (!docs.length) continue;
    out.push('## ' + heading);
    out.push(docs.map((d) => {
      const line = `- [${escLabel(d.title)}](${d.path})`;
      return d.summary ? `${line}: ${d.summary}` : line;
    }).join('\n'));
  }
  out.push(GENERATED_BY);
  return out.join('\n\n') + '\n';
}

/** The same public corpus, whole. Returns null when the result would exceed the size guard —
 *  never a truncated file, because a truncated dump is indistinguishable from a complete one. */
export function buildLlmsFullTxt(corpus, origin) {
  const site = corpus.site || {};
  const out = ['# ' + String(site.name || '').trim()];
  const description = String(site.description || '').trim();
  if (description) out.push('> ' + description);
  for (const doc of publicDocs(corpus)) out.push(documentMarkdown(doc, origin).trim());
  out.push(GENERATED_BY);
  const text = out.join('\n\n') + '\n';
  return new TextEncoder().encode(text).length > LLMS_FULL_MAX_BYTES ? null : text;
}

/** The L1 discovery list. Every optional target this build did not actually produce is `null`, so
 *  no entry here can point at a URL nothing serves. */
export function buildAiCatalog(corpus, { llmsFull, hasRobots }) {
  const site = corpus.site || {};
  return {
    version: 1,
    generator: 'feelreef',
    site: String(site.origin || site.name || ''),
    robots: hasRobots ? '/robots.txt' : null,
    llms: '/llms.txt',
    llms_full: llmsFull ? '/llms-full.txt' : null,
    markdown: { negotiation: true },
    sitemap: '/sitemap.xml',
    mcp: null,
  };
}

/** The internal public-route → markdown-asset mapping the site worker consumes. It is exactly the
 *  set of public content routes this build emitted a markdown file for — a worker reading it never
 *  reconstructs a URL family, and nothing private or forwarded can enter it.
 *
 *  🔴 EDGE-RENDERED routes are NOT excluded here, and cannot be: a storefront page is a content
 *  page like any other (the build derives its descriptor from the same IR page), so `/shop` and
 *  each locale's `/xx/shop` legitimately appear in this set. Which of them the worker answers
 *  itself is a fact only the emitter holds — `--storefronts` / the contract's siteOwnedBuyerPages —
 *  so emit-shop-function.mjs's loadMarkdownManifest is where they are dropped, naming each one. */
export function buildMarkdownMapping(corpus) {
  return {
    schemaVersion: 1,
    routes: publicDocs(corpus).map((d) => ({ path: d.path, asset: markdownAsset(d.path) })),
  };
}

/** Everything one build emits, from the resolved gate and the corpus. The whole "which files
 *  exist" decision lives here rather than in the route files, so a plain `node --test` can prove
 *  gate-off emits nothing and a hand-written llms.txt suppresses only ours.
 *  `assetExists` takes a path relative to the site's assets overlay root. */
export function agentBundle(corpus, { gate, origin = '', assetExists = () => false } = {}) {
  const empty = { llms: null, llmsFull: null, catalog: null, mapping: null, markdown: new Map() };
  if (!gate || !gate.generate) return empty;
  const withOrigin = { ...corpus, site: { ...(corpus.site || {}), origin } };
  const llmsFull = buildLlmsFullTxt(withOrigin, origin);
  return {
    // A hand-written llms.txt is the owner's answer and ships through their assets untouched. The
    // catalog still points at /llms.txt, because that path is served either way.
    llms: gate.manualLlms ? null : buildLlmsTxt(withOrigin),
    llmsFull,
    catalog: buildAiCatalog(withOrigin, { llmsFull, hasRobots: assetExists('robots.txt') }),
    mapping: buildMarkdownMapping(withOrigin),
    markdown: new Map(publicDocs(withOrigin).map((doc) => [doc.path, documentMarkdown(doc, origin)])),
  };
}

/** Every path this generator writes, for the collision gate. `llms.txt` is absent on purpose: a
 *  hand-written one is the owner's answer and wins through the build's manual flag, exactly as a
 *  hand-written robots.txt does. Nothing hand-writes a full-corpus dump, a catalog whose targets we
 *  generate, or a page's markdown twin — so those fail the build rather than race over one path. */
export function generatorOwnedPaths(corpus) {
  return [
    '/llms-full.txt',
    '/.well-known/ai-catalog.json',
    '/reef-agent-markdown.json',
    ...publicDocs(corpus).map((d) => markdownAsset(d.path)),
  ];
}

/** Fail closed when the site's own assets already carry a path this generator writes. `exists`
 *  takes a path relative to the assets overlay root and is injected, so this stays testable. */
export function assertNoAssetCollision(corpus, exists) {
  for (const path of generatorOwnedPaths(corpus)) {
    if (exists(path.replace(/^\//, ''))) {
      throw new Error(
        `this site's assets already carry ${path}, which this build generates — remove or rename it: `
        + 'a generated artifact must never silently clobber the owner\'s file, and two writers on one '
        + 'path is not a state a deployed site can be honest about.',
      );
    }
  }
}

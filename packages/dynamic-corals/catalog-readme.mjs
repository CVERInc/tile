import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CORALS } from './corals.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
export const START = '<!-- coral metadata: start (generated by catalog-readme.mjs) -->';
export const END = '<!-- coral metadata: end -->';

export function renderMetadata(name, metadata) {
  const rows = metadata.attributes.map(({ name: attribute, type, required, default: fallback, description }) =>
    `| \`${attribute}\` | ${type} | ${required ? 'yes' : 'no'} | ${fallback === null ? '—' : `\`${String(fallback).replaceAll('|', '\\|')}\``} | ${description.replaceAll('|', '\\|')} |`);
  return [START, `## ${name} metadata`, '', metadata.summary, '', `Author: \`${metadata.author}\`.`, '',
    ...(metadata.host ? [`Host: \`${metadata.host}\`. ${metadata.requirements}`, ''] : []),
    ...(metadata.anyOf ? ['Requires one of: ' + metadata.anyOf.map(group => group.map(a => '`' + a + '`').join(' + ')).join(' or ') + '.', ''] : []),
    '### Embed', '', '```html', metadata.embed, '```', '', '### Attributes', '',
    '| Attribute | Type | Required | Default | Purpose |', '|---|---|---|---|---|', ...rows,
    '', END].join('\n');
}

export function expectedReadme(name, metadata, current) {
  const block = renderMetadata(name, metadata);
  const start = current.indexOf(START);
  const end = current.indexOf(END);
  if (start === -1 && end === -1) return `${current.trimEnd()}\n\n${block}\n`;
  if (start === -1 || end < start || current.indexOf(START, start + 1) !== -1 || current.indexOf(END, end + 1) !== -1) {
    throw new Error(`${name}: malformed generated README section`);
  }
  return current.slice(0, start) + block + current.slice(end + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const write = process.argv[2] === '--write';
  if (!write && process.argv[2] !== '--check') throw new Error('Usage: node catalog-readme.mjs --write|--check');
  let drift = 0;
  for (const name of Object.keys(CORALS)) {
    const dir = join(HERE, name);
    const metadata = JSON.parse(readFileSync(join(dir, 'metadata.json'), 'utf8'));
    const readme = join(dir, 'README.md');
    let current = '';
    try { current = readFileSync(readme, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    const expected = expectedReadme(name, metadata, current);
    if (current === expected) continue;
    if (write) writeFileSync(readme, expected);
    else { console.error(`${name}: README metadata drift`); drift++; }
  }
  if (drift) process.exitCode = 1;
}

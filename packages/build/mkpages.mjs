// mkpages — build a sitetile `site_pages` JSON ([{path,markdown}]) from an owned IR dir.
// General (any sitetile site). Walks <ir-dir> recursively for *.md, maps:
//   <ir>/home.md            → path "home"   (route /)
//   <ir>/about.md           → path "about"  (route /about)
//   <ir>/legal/terms.md     → path "legal/terms" (nested route preserved)
//   <ir>/<loc>/home.md      → path "<loc>"  (locale home, route /<loc>/)
// Excludes a posts/ subdir by default (that's the Blog package's --blog dir, shipped separately).
//
// Usage: node mkpages.mjs <ir-dir> [out.json] [--include-posts]
//   prints to stdout if no out.json.
//
// 🔴 THE CLI CONTRACT AND THE BYTES ARE THE API. This file arrived from a private checkout, and a
// private runner drops it into a container by path and runs it exactly as above; its JSON is then
// read by a deploy script that is not in this repo. So the argument shape, the exit codes, the
// stderr line and the exact `JSON.stringify(pages, null, 2)` bytes are all load-bearing, and
// packages/build/collect-pages.test.mjs holds them to a fixture
// generated by the pre-move original. What is NEW here is only the `collectPages` export and the
// entrypoint guard that keeps the CLI from firing when something imports it.
//
// 🔴 It does NOT sanitise a path segment, and that is deliberate rather than missing: this half
// emits DATA. The moment a path becomes a filename is in stage.mjs, and that is where the
// sanitising belongs — see this package's README.
import fs from 'fs'; import path from 'path';
import { pathToFileURL } from 'node:url';

/**
 * Collect an IR directory into the `site_pages` shape: `[{path, markdown}]`, sorted by path.
 *
 * @param {string} irDir              the site's IR directory (the one holding home.md)
 * @param {{includePosts?: boolean}} [options]  keep `posts(-|$)/` dirs as pages too
 * @returns {{path: string, markdown: string}[]}
 */
export function collectPages(irDir, { includePosts = false } = {}) {
  function walk(dir) {
    const acc = [];
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (e.isDirectory()) {
        // exclude any blog-corpus dir (posts, posts-full, …) — those ship via --blog, not as pages
        if (!includePosts && /^posts(-|$)/.test(e.name)) continue;
        acc.push(...walk(path.join(dir, e.name)));
      } else if (e.isFile() && e.name.endsWith('.md')) {
        // `_theme.md` is the structured THEME source. The compiled theme.css the build stages under
        // the name `theme:` asks for is made by the platform and travels with the export beside
        // ir/ — nothing in this repo compiles it. Either way this is NOT a content page and must
        // not enter
        // site_pages.json (it would bloat the JSON with the residue block and, pre-renderer-guard,
        // route as a bogus /_theme page). `_site.md` DOES stay — the renderer reads it as config.
        if (e.name === '_theme.md') continue;
        acc.push(path.join(dir, e.name));
      }
    }
    return acc;
  }

  return walk(irDir).map((file) => {
    const rel = path.relative(irDir, file).replace(/\.md$/, '');     // e.g. "home", "legal/terms", "zh-tw/about"
    const segs = rel.split(path.sep);
    // home.md → "home"; <loc>/home.md → "<loc>" (locale home). Otherwise keep the nested path.
    let p;
    if (segs[segs.length - 1] === 'home') p = segs.slice(0, -1).join('/') || 'home';
    else p = segs.join('/');
    return { path: p, markdown: fs.readFileSync(file, 'utf8') };
  }).sort((a, b) => a.path.localeCompare(b.path));
}

// ── the CLI, unchanged from the original, and only when this file IS the entrypoint ─────────────
//
// 🩸 REALPATH BOTH SIDES, and that is the whole of this helper. `pathToFileURL()` only resolves a
// path; the ESM loader hands `import.meta.url` a REALPATH. So the moment any segment of the
// invoking path is a symlink — a mount point, macOS's `/tmp` → `/private/tmp`, a vendored link, a
// runner that drops this file in by path — the two are unequal, the block below never runs, and the
// CLI becomes a silent no-op: 0 bytes on stdout, exit 0, empty stderr, and a downstream reader
// holding an empty out.json with nothing to tell it why. Measured 2026-09-07:
//   ln -s "$PWD/mkpages.mjs" link.mjs && node link.mjs <ir-dir>   → 0 bytes, exit 0
// How the path is spelled belongs to the CALLER, so this side must not depend on it.
const isEntrypoint = () => {
  if (!process.argv[1]) return false;
  try { return import.meta.url === pathToFileURL(fs.realpathSync(process.argv[1])).href; }
  catch { return false; }   // an argv[1] that will not resolve is not this file
};

if (isEntrypoint()) {
  const [, , irDir, outArg] = process.argv;
  const includePosts = process.argv.includes('--include-posts');
  if (!irDir) { console.error('usage: node mkpages.mjs <ir-dir> [out.json] [--include-posts]'); process.exit(2); }
  const out = (outArg && !outArg.startsWith('--')) ? outArg : null;

  const pages = collectPages(irDir, { includePosts });
  const json = JSON.stringify(pages, null, 2);
  if (out) { fs.writeFileSync(out, json); console.error(`▸ wrote ${pages.length} page(s) → ${out}`); }
  else process.stdout.write(json);
}

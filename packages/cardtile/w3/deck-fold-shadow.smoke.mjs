const r2 = (x) => Math.round(x * 100) / 100;

async function open({ reduced = false } = {}) {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, reducedMotion: reduced ? 'reduce' : 'no-preference' });
  const page = await ctx.newPage();
  await page.route('**/*', async (route) => {
    const u = new URL(route.request().url());
    if (u.host !== 'card.test') return route.abort();
    if (/^\/_icon\//.test(u.pathname)) return route.fulfill({ contentType: 'image/png', body: PIXEL });
    const r = await worker.fetch(new Request('http://x' + u.pathname + u.search), { CARDS: store, PREVIEW: 'true' });
    const headers = Object.fromEntries(r.headers); delete headers['content-length'];
    return route.fulfill({ status: r.status, headers, body: Buffer.from(await r.arrayBuffer()) });
  });
  await page.goto('http://card.test/fold');
  await page.waitForFunction(() => window.__deckBoot === 'ready' || !!document.querySelector('.deck-seg button'), null, { timeout: 15000 });
  await page.waitForTimeout(1800);   // the deal is over
  await page.mouse.move(2, 2);       // nothing is hovered
  // what every reading below is made of: the ground shadow's opacity, and where each card of the table is
  await page.evaluate(() => {
    window.__read = () => ({ g: parseFloat(getComputedStyle(document.querySelector('.deck-gshadow')).opacity),
      fan: document.documentElement.classList.contains('fan'),
      // the cards that are drawn and carry an edge shadow of their own
      edged: [...document.querySelectorAll('.deck-stack > .deck-card')].filter((c) => { const s = getComputedStyle(c); if (s.visibility !== 'visible' || parseFloat(s.opacity) < 0.01) return false; const b = getComputedStyle(c.querySelector('.deck-face')).boxShadow; const m = /rgba?\(([^)]+)\)/.exec(b); if (!m) return false; const p = m[1].split(',').map(parseFloat); return (p.length < 4 ? 1 : p[3]) > 0.01; }).length,
      at: [...document.querySelectorAll('.deck-stack > .deck-card')].map((c) => { const r = c.getBoundingClientRect(); return [r.left + r.width / 2, r.top + r.height / 2]; }) });
  });
  return { ctx, page };
}
const rest = (page) => page.evaluate(() => window.__read().g);
const fanOpen = async (page) => { await page.evaluate(() => window.__deckFan()); await page.waitForTimeout(700); if (!(await page.evaluate(() => window.__read().fan))) throw new Error('the fan did not open'); };

// the cards' share of the way from where they were (`a`) to where they end (`b`), 0…1: the mean over the cards that move
const way = (a, b, now) => { let s = 0, n = 0; for (let i = 0; i < a.length; i++) { const d = Math.hypot(b[i][0] - a[i][0], b[i][1] - a[i][1]); if (d < 4) continue; s += 1 - Math.hypot(b[i][0] - now[i][0], b[i][1] - now[i][1]) / d; n++; } return n ? s / n : 1; };

// the page's picture with the ground shadow taken out: what is left is the cards and the shadows they carry themselves
const bare = async (page) => { const tag = await page.addStyleTag({ content: '.deck-gshadow{visibility:hidden!important}' }); const png = await page.screenshot(); await tag.evaluate((n) => n.remove()); return png; };

// Toggle the fan with its timers held back, then stop its animations at each time in `stops` (ms of the motion's own
// clock) and read. `shot` also takes the page's picture at the last stop. The held timers run afterwards.
async function stopped(page, stops, shot) {
  await page.evaluate(() => { const real = window.setTimeout; window.__held = []; window.setTimeout = (f) => { window.__held.push(f); return 0; }; try { window.__deckFanToggle(); } finally { window.setTimeout = real; } });
  const rows = [];
  for (const t of stops) { rows.push({ t, ...(await page.evaluate((t) => { for (const a of document.getAnimations()) { a.pause(); a.currentTime = t; } return window.__read(); }, t)) }); if (FRAMES && shot) writeFileSync(join(FRAMES, `${shot}-${String(t).padStart(3, '0')}.png`), await page.screenshot()); }
  const end = await page.evaluate(() => { for (const a of document.getAnimations()) a.finish(); return window.__read(); });
  const picture = shot ? await bare(page) : null;
  await page.evaluate(() => { for (const f of window.__held) f(); window.__held = []; });
  await page.waitForTimeout(300);
  return { rows, end, picture };
}
const print = (title, rows, g0) => { if (!TABLE) return; console.log(`   ${title}\n   | t (ms) | cards: share of the way | ground shadow opacity | share of its resting opacity |\n   |---:|---:|---:|---:|`); for (const r of rows) console.log(`   | ${Math.round(r.t)} | ${r.way.toFixed(2)} | ${r.g.toFixed(3)} | ${(r.g / g0).toFixed(2)} |`); };

// the fold rule, for one reading
const foldRule = (name, r, g0) => { const share = r.g / g0;
  check(`${name}: at ${Math.round(r.t)} ms the shadow is not ahead of the cards`, share <= r.way + 0.03, `shadow ${r2(share)} of its rest, cards ${r2(r.way)} of the way home`);
  if (r.way < 0.5) check(`${name}: at ${Math.round(r.t)} ms, cards not half way home, there is no shadow yet`, share <= 0.02, `shadow ${r2(share)} of its rest, cards ${r2(r.way)} of the way home`); };


// The pile's shadow belongs to the cards — in a real browser, because the unit suite (w3/deck-views.test.mjs) runs the
// deck in a stand-in DOM with no layout, no paint and no animation clock.
//
// A fan folds back into the pile in 500 ms (deck.js fanIn). The shadow the pile throws on the table (.deck-gshadow) used
// to start fading in at the pile's place the moment the fold began, while every card was still down in the fan: a shadow
// with nothing over it. And every fan card stays drawn until the fold is over, each with its own edge shadow, where the
// resting pile draws three.
//
//   fold    FOLDING, THE GROUND SHADOW NEVER PRECEDES THE CARDS. The fold is stopped at every 50 ms of its own clock (the
//           page's animations paused and set to that time; the timers the fold starts are held back). At each stop the
//           shadow's share of its resting opacity is at most the cards' share of the way home, it is nothing at all
//           while the cards are in the first half of the way, and it is whole when they have landed.
//   pile    THE CARDS CLOSING IN ARE NO DARKER THAN THE PILE. From the middle of the fold on, no more of the cards that
//           are drawn carry an edge shadow than the resting pile shows (the ones it will hide have put theirs down: they
//           overlap as they close in, and their shadows added up to 28 of 255 darker over about a thousand pixels). And
//           the picture of the page at the fold's last moment (every fan card home and still drawn) is the picture of
//           the pile at rest, pixel for pixel, with the ground shadow taken out of both.
//   open    OPENING, THE GROUND SHADOW LEAVES WITH THE CARDS: stopped every 50 ms, it is never left behind (what is left
//           of it is at most what is left of the cards' way out, with a little slack), and it is gone when they arrive.
//   live    THE SAME, UNSTOPPED: Escape folds a fan, and a click on a fan card picks it (deck.js fanPick, which folds
//           too); every animation frame is read as it plays and held to the fold rule.
//   still   UNDER prefers-reduced-motion the shadow does not animate: it is simply there from the fold's first moment.
//
//   PLAYWRIGHT=/path/to/playwright/index.js node packages/cardtile/w3/deck-fold-shadow.smoke.mjs [<base URL>]
//   … --engine chromium|webkit   (default chromium)
//   … --only fold|pile|open|live|still
//   … --table                    print every stop: time, the cards' way, the shadow
//   … --frames <dir>             also write the picture of every stop of the fold to <dir>
//
// The base URL scripts/test.sh hands every browser smoke is accepted and not used: the page is the cardtile worker's
// own (serve/card-worker.mjs, answered in-process through page.route), so the deck is the generated bytes production
// serves, not the sources beside this file — regenerate (serve/gen-edit3-assets.mjs) before reading a result.
// Exits 1 on any failure, 2 when the browser does not launch.

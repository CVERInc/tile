// the cards' share of the way from where they were (`a`) to where they end (`b`), 0…1: the mean over the cards that move
const way = (a, b, now) => { let s = 0, n = 0; for (let i = 0; i < a.length; i++) { const d = Math.hypot(b[i][0] - a[i][0], b[i][1] - a[i][1]); if (d < 4) continue; s += 1 - Math.hypot(b[i][0] - now[i][0], b[i][1] - now[i][1]) / d; n++; } return n ? s / n : 1; };


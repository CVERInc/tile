// Bundle the Card editor (packages/cardtile/w3) and the deck every Card page carries into importable
// ES modules, so the edge Worker can serve `card.feelreef.com/try/edit`, `/edit?host=` and every Card
// page without touching a filesystem (Workers can't).
//
//   node packages/cardtile/serve/gen-edit3-assets.mjs
//
// Read the real files, bundle what needs bundling, write TWO generated modules. Both are committed —
// Workers deploy from source, not from a build step.
//
//   serve/deck-assets.mjs   w3/deck.js + w3/deck.css, and their version (the live page's /_deck/ path)
//   serve/edit3-assets.mjs  the editor: its markup, its two stylesheets, its module, the files it
//                           borrows, and the porch faces
//
// 🔴 ORDER MATTERS. deck-assets.mjs is written BEFORE the editor is bundled: the editor's preview is
// renderCardHTML, which names the deck's versioned path, so the bundle reads deck-assets.mjs — and it
// must read the one these sources make, not the previous run's.
//
// ── WHAT THE EDITOR BORROWS, AND WHERE FROM ──────────────────────────────────────────────────────
// Served unmodified, each under its own content hash (/try/edit/a/<hash>/<name>, immutable):
//   hosts/web/modaltile/vendor/editor-core.js   the family text editor (modaltile and tugtile write with it)
//   packages/core/obsidian-shim.js              lets that Obsidian-flavoured editor run in a browser
//   packages/core/web-host.js                   its minimal web host
//   styles.css                                  the family stylesheet the editor is mounted with …
//   hosts/web/modaltile/modaltile.css           … and modaltile's, exactly as modaltile mounts it
//   hosts/web/tugtile/Sortable.min.js           the drag engine, loaded INSIDE the wall's frame
import esbuild from 'esbuild';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';
import { sourceStamp, contentHash, isOwnOutput } from './edit3-sources.mjs';
import { DECK_STRINGS, DECK_AWAITING_DECK_JS } from '../w3/deck-i18n.mjs';

const DIR = dirname(fileURLToPath(import.meta.url));
const W3 = join(DIR, '../w3');
const ROOT = join(DIR, '../../..');   // this repo's own root

// 🔴 every file this generator opens goes through here (or comes out of esbuild's metafile below)
// and lands in SOURCE_FILES, which the stale-bundle stamp is computed over. Do not call
// fs.readFileSync on a bundle input directly.
const READ = new Set();
const rd = (p, enc) => {
  if (!fs.existsSync(p)) throw new Error(`gen-edit3-assets: ${relative(ROOT, p)} is missing`);
  READ.add(relative(DIR, p).split('\\').join('/'));
  return fs.readFileSync(p, enc);
};
const HEADER = (what) => `// GENERATED by gen-edit3-assets.mjs — do not edit. ${what}\n// Regenerate: node packages/cardtile/serve/gen-edit3-assets.mjs\n`;

// ── 1. the deck ───────────────────────────────────────────────────────────────────────────────────
const DECK_JS = rd(join(W3, 'deck.js'), 'utf8');
const DECK_CSS = rd(join(W3, 'deck.css'), 'utf8');
// a tag the deck never names would leave a visitor with an empty label, so it is checked here
// (DECK_AWAITING_DECK_JS: the keys whose call sites in deck.js are not switched over yet — allowed
// unsaid, and refused once said, so that list is deleted by the change that uses them)
for (const k of Object.keys(DECK_STRINGS.en)) {
  const said = DECK_JS.includes(`say('${k}')`);
  if (k in DECK_AWAITING_DECK_JS) {
    if (said) throw new Error(`gen-edit3-assets: deck.js says ${k} now — take it off DECK_AWAITING_DECK_JS`);
  } else if (!said) throw new Error(`gen-edit3-assets: deck-i18n.mjs has ${k}, which deck.js never says`);
}
for (const m of DECK_JS.matchAll(/say\('(\w+)'\)/g)) {
  if (!(m[1] in DECK_STRINGS.en)) throw new Error(`gen-edit3-assets: deck.js says ${m[1]}, which deck-i18n.mjs does not have`);
}
const DECK_VERSION = contentHash(DECK_JS + '\n/*css*/\n' + DECK_CSS);
fs.writeFileSync(join(DIR, 'deck-assets.mjs'), `${HEADER('The deck every Card page carries (w3/deck.js, w3/deck.css).')}
export const DECK_JS = ${JSON.stringify(DECK_JS)};
export const DECK_CSS = ${JSON.stringify(DECK_CSS)};
/** a hash of both — the version segment of /_deck/deck-<version>.{js,css} */
export const DECK_VERSION = ${JSON.stringify(DECK_VERSION)};
`);

// ── 2. the editor's module ────────────────────────────────────────────────────────────────────────
// ESM, because the module awaits the borrowed editor at its top level; served as one inline
// <script type="module">. The borrowed files stay runtime imports (their URLs come from the page).
const bundled = await esbuild.build({
  entryPoints: [join(W3, 'edit3.mjs')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  write: false,
  metafile: true,
  logLevel: 'silent',
});
if (bundled.errors?.length) {
  throw new Error('gen-edit3-assets: bundle failed:\n' + bundled.errors.map((e) => e.text).join('\n'));
}
const EDIT3_JS = bundled.outputFiles[0].text;
// an inline module ends at the first `</script` it contains, wherever it is
if (/<\/script/i.test(EDIT3_JS)) throw new Error('gen-edit3-assets: the bundle contains </script — it cannot be inlined');
const OUT_INPUTS = Object.values(bundled.metafile.outputs)[0].inputs;
for (const k of Object.keys(bundled.metafile.inputs)) {
  // 🔴 This generator's OWN previous output may be in the graph (card-worker.mjs imports
  // edit3-assets.mjs) but esbuild must keep none of it: a bundle carrying bytes of the file being
  // written would embed a previous copy of itself.
  if (isOwnOutput(join(process.cwd(), k), DIR)) {
    if (OUT_INPUTS[k] && OUT_INPUTS[k].bytesInOutput > 0) throw new Error('gen-edit3-assets: the bundle carries bytes of edit3-assets.mjs — it would embed its own previous output');
    continue;
  }
  READ.add(relative(DIR, join(process.cwd(), k)).split('\\').join('/'));   // metafile keys are relative to esbuild's cwd
}

// ── 3. the borrowed files and the faces, each under its content hash ─────────────────────────────
const BORROW = {
  'editor-core.js': 'hosts/web/modaltile/vendor/editor-core.js',
  'obsidian-shim.js': 'packages/core/obsidian-shim.js',
  'web-host.js': 'packages/core/web-host.js',
  'family.css': 'styles.css',
  'modaltile.css': 'hosts/web/modaltile/modaltile.css',
  'Sortable.min.js': 'hosts/web/tugtile/Sortable.min.js',
};
const BORROWED = Object.fromEntries(Object.entries(BORROW).map(([name, rel]) => {
  const body = rd(join(ROOT, rel), 'utf8');
  return [name, { hash: contentHash(body), body }];
}));
if (!/export\s*\{[^}]*mountEditor/.test(BORROWED['editor-core.js'].body)) throw new Error('gen-edit3-assets: editor-core.js no longer exports mountEditor');
if (!/export function makeWebHost/.test(BORROWED['web-host.js'].body)) throw new Error('gen-edit3-assets: web-host.js no longer exports makeWebHost');

const FONT_BASE = '/try/edit/a/';
const FONT_NAMES = ['NunitoVariable-latin.woff2', 'NunitoVariable-latin-ext.woff2', 'YoungSerif-latin.woff2', 'YoungSerif-latin-ext.woff2'];
const FONT_FILES = Object.fromEntries(FONT_NAMES.map((f) => {
  const bytes = rd(join(W3, 'fonts', f));
  return [`fonts/${f}`, { hash: contentHash(bytes), b64: bytes.toString('base64') }];
}));
let PORCH_FONTS_CSS = rd(join(W3, 'porch-fonts.css'), 'utf8');
for (const [path, { hash }] of Object.entries(FONT_FILES)) PORCH_FONTS_CSS = PORCH_FONTS_CSS.replaceAll(`url(./${path})`, `url(${FONT_BASE}${hash}/${path})`);
if (PORCH_FONTS_CSS.includes('url(./')) throw new Error('gen-edit3-assets: porch-fonts.css has a relative url the rewrite missed');

// ── 4. the stylesheets, in cascade order ─────────────────────────────────────────────────────────
// before the family editor's two stylesheets: the shared sheet chrome, the porch tokens and faces,
// and the porch skin; after them (so it wins where they overlap): the editor's own layout.
// bleedblend is the repo's own edge-bar classes (the notice wears .bleedblend-top / -bottom, -push) so iOS
// Safari tints its chrome to the bar — read from where sitetile ships it, never copied.
const EDIT3_BASE_CSS = [
  rd(join(DIR, '../w/editor.css'), 'utf8'),
  rd(join(ROOT, 'packages/sitetile/astro/src/packages/bleedblend/style.css'), 'utf8'),
  rd(join(W3, 'porch-tokens.css'), 'utf8'),
  PORCH_FONTS_CSS,
  rd(join(W3, 'porch.css'), 'utf8'),
].join('\n');
const EDIT3_CSS = rd(join(W3, 'edit3.css'), 'utf8');
for (const [name, css] of [['the base stylesheet', EDIT3_BASE_CSS], ['edit3.css', EDIT3_CSS]]) {
  if (/<\/style/i.test(css)) throw new Error(`gen-edit3-assets: ${name} contains </style — it cannot be inlined`);
}

// ── 5. the markup ────────────────────────────────────────────────────────────────────────────────
// w3/index.html is the <body> only; its leading comment is for whoever reads the file, not the page.
const BODY = rd(join(W3, 'index.html'), 'utf8').replace(/^\s*<!--[\s\S]*?-->\s*/, '');
for (const id of ['editbtn', 'row', 'deckframe', 'gridframe', 'modal', 'doormodal', 'leavemodal', 'notice-top', 'notice-bottom']) {
  if (!BODY.includes(`id="${id}"`)) throw new Error(`gen-edit3-assets: w3/index.html has no #${id} — the editor would miss it`);
}

// 🔴 the generator and the stamp's own module are inputs too — they decide what is emitted
READ.add('gen-edit3-assets.mjs'); READ.add('edit3-sources.mjs');
const SOURCE_FILES = [...READ].sort();
const out = `${HEADER('The Card editor (packages/cardtile/w3), bundled for the edge Worker.')}// See gen-edit3-assets.mjs for what is and is not committed here.
export const EDIT3_BODY_HTML = ${JSON.stringify(BODY)};
/** before the family stylesheets: w/editor.css, the porch tokens and faces, the porch skin */
export const EDIT3_BASE_CSS = ${JSON.stringify(EDIT3_BASE_CSS)};
/** after them: the editor's own layout */
export const EDIT3_CSS = ${JSON.stringify(EDIT3_CSS)};
export const EDIT3_JS = ${JSON.stringify(EDIT3_JS)};
/** the files the editor borrows as they ship: name → { hash, body } */
export const BORROWED = ${JSON.stringify(BORROWED)};
/** the porch faces: path → { hash, b64 } */
export const FONT_FILES = ${JSON.stringify(FONT_FILES)};
/** a hash of the SOURCES this was built from — see edit3-sources.mjs, and the test that recomputes it */
export const SOURCE_STAMP = ${JSON.stringify(sourceStamp(SOURCE_FILES))};
/** every file the generator read (paths relative to serve/) — the stamp above is over exactly these */
export const SOURCE_FILES = ${JSON.stringify(SOURCE_FILES, null, 0)};
`;
fs.writeFileSync(join(DIR, 'edit3-assets.mjs'), out);
console.log('wrote deck-assets.mjs — deck', DECK_VERSION, '| js', DECK_JS.length, '| css', DECK_CSS.length);
console.log('wrote edit3-assets.mjs — body', BODY.length, '| css', EDIT3_BASE_CSS.length, '+', EDIT3_CSS.length,
            '| edit3.js bundle', EDIT3_JS.length, '| borrowed',
            Object.entries(BORROWED).map(([k, v]) => `${k}:${v.body.length}`).join(' '),
            '| fonts', Object.values(FONT_FILES).reduce((n, f) => n + f.b64.length, 0), 'base64 chars',
            '| sources', SOURCE_FILES.length);

/** Every locale key both tables above must carry — the single list the tests check against. */
export const LOCALE_KEYS = Object.keys(SANDBOX_LOCALES);

/**
 * A single BCP-47 tag (already split off `Accept-Language`, or a bare `?lang=`/`?locale=` value) →
 * the locale KEY this editor knows, or `null` when nothing matches.
 *
 * Chinese needs its own disambiguation: the primary subtag `zh` is not enough to tell Traditional
 * from Simplified apart, so a full-tag check runs first — `hans`/`cn`/`sg` anywhere in the tag (script
 * or region subtag) means Simplified; anything else beginning `zh` (`zh-TW`, `zh-Hant`, `zh-HK`,
 * `zh-MO`, or bare `zh`) keeps meaning Traditional, matching this table's ORIGINAL single `zh` key
 * before Simplified existed — so a plain `zh` never silently switches meaning underneath existing
 * links/bookmarks.
 */
function resolveLocaleKey(tag) {
  const t = String(tag || '').trim().toLowerCase();
  if (!t) return null;
  const subtags = t.split(/[-_]/);
  const primary = subtags[0];
  if (primary === 'zh') {
    return (subtags.includes('hans') || subtags.includes('cn') || subtags.includes('sg')) ? 'zh-Hans' : 'zh';
  }
  return SANDBOX_LOCALES[primary] ? primary : null;
}

/** Any BCP-47 tag → the locale key this editor knows, or `'en'` when we have nothing. */
export function primaryLocale(tag) {
  return resolveLocaleKey(tag) || 'en';
}

/**
 * `Accept-Language` (as the header arrives — `ja,en-US;q=0.9,zh-TW;q=0.8`) → the best locale key we
 * speak. First candidate we recognise wins; quality weights are read as WRITTEN ORDER, which is what
 * every browser already sends (highest q first) — parsing q values would be solving a problem this
 * header does not have. Each candidate is checked as a FULL tag (not just its primary subtag), so
 * `zh-CN` in the header resolves to Simplified even though `zh-TW` earlier/later in the same header
 * resolves to Traditional.
 */
export function localeFromAcceptLanguage(header) {
  for (const part of String(header || '').split(',')) {
    const tag = part.split(';')[0].trim();
    if (!tag) continue;
    const key = resolveLocaleKey(tag);
    if (key) return key;
  }
  return 'en';
}

/** The editor CHROME strings for a locale key, falling back to English for anything unrecognised. */
export function chromeStrings(localeKey) {
  return CHROME_STRINGS[localeKey] || CHROME_STRINGS.en;
}

/**
 * The sandbox's starter card, seeded fresh — a neutral persona, never a real person, same shape as
 * the retired route's `buildSandboxCard`: a profile with the one-line bio, and one link.
 *
 * 🔴 NO "tap to edit" TEXT TILE. It used to be the third cell, and it was an instruction wearing a
 * tile's clothes — a visitor who claimed the card took a sentence about the editor home with them.
 * Instructions about the editor live in the EDITOR (`coachMark`, shown once beside the card by
 * w2/edit2.mjs); the card holds only what a card would hold. `textBody` stays in the table because
 * the vocabulary tests read the unit word from it, but nothing seeds it any more.
 */
export function buildSandboxCard(localeKey) {
  const p = SANDBOX_LOCALES[primaryLocale(localeKey)];
  return [
    '---',
    'card-page: try',
    `title: ${p.name}`,
    `lang: ${p.lang}`,
    '---',
    '',
    '## cards',
    '',
    `- [ ] %% card: profile w=6 %% ${p.bio}`,
    `- [ ] %% card: link w=3 %% [${p.linkLabel}](https://example.com)`,
  ].join('\n') + '\n';
}
